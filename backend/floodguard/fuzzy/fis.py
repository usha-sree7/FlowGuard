"""Rule base plus Type-1 and Interval Type-2 inference engines sharing the same variables and rules.

Inputs  : level [m], rise [m/h], rain [accumulated fused rain over the rain window]
Terms   : level  {Low, Elevated, High, VeryHigh}
          rise   {Falling, Steady, Rising, RisingFast}
          rain   {None, Light, Moderate, Heavy}
Output  : risk score 0-100 with consequents {Normal, Watch, Warning, Critical}
Rules   : complete 4x4x4 = 64-rule grid generated by `rule_severity` (printed in docs/MATHEMATICAL_MODEL.md)
T-norm  : product.  IT2: center-of-sets type reduction (Karnik-Mendel) + midpoint defuzzification.
T1      : same rules, embedded Type-1 MFs, center-of-sets weighted average with the consequent midpoints.
"""
from __future__ import annotations

import itertools
from dataclasses import dataclass

import numpy as np

from .km import type_reduce


INPUTS = ("level", "rise", "rain")
TERMS = {
    "level": ("Low", "Elevated", "High", "VeryHigh"),
    "rise": ("Falling", "Steady", "Rising", "RisingFast"),
    "rain": ("None", "Light", "Moderate", "Heavy"),
}
OUTPUT_TERMS = ("Normal", "Watch", "Warning", "Critical")
# Consequent centroid intervals on the 0-100 risk scale (interval consequents -> genuine COS type reduction).
CONSEQUENTS = {"Normal": (5.0, 15.0), "Watch": (32.0, 43.0), "Warning": (57.0, 68.0), "Critical": (85.0, 95.0)}


def rule_severity(L: int, R: int, P: int) -> int:
    """Expert rule template (indices: 0 = lowest term). Level drives the base severity; fast or
    rain-supported rises escalate; a receding level with no rain de-escalates one step."""
    s = L
    if R == 3 or (R == 2 and P >= 2):
        s += 1
    if P == 3 and R >= 2 and L >= 1:
        s += 1
    if R == 0 and P == 0 and L in (1, 2):
        s -= 1
    if P == 3 and L == 0:
        s = max(s, 1)
    return int(np.clip(s, 0, 3))


RULES = [(L, R, P, rule_severity(L, R, P)) for L, R, P in itertools.product(range(4), repeat=3)]


def rule_table() -> list[dict]:
    return [{"if": {"level": TERMS["level"][L], "rise": TERMS["rise"][R], "rain": TERMS["rain"][P]},
             "then": OUTPUT_TERMS[s]} for L, R, P, s in RULES]


@dataclass
class FIS:
    mfs: dict  # input name -> list[IT2Trap] (4 terms)

    def _rule_arrays(self):
        ant = np.array([[L, R, P] for L, R, P, _ in RULES])
        cons = np.array([s for *_, s in RULES])
        cl = np.array([CONSEQUENTS[OUTPUT_TERMS[s]][0] for s in cons])
        cr = np.array([CONSEQUENTS[OUTPUT_TERMS[s]][1] for s in cons])
        return ant, cl, cr

    def term_memberships_it2(self, intervals: dict):
        """intervals: name -> (lo, hi) arrays. Returns name -> (mu_lo (N,4), mu_hi (N,4))."""
        out = {}
        for name in INPUTS:
            lo, hi = (np.asarray(v, float) for v in intervals[name])
            ml = np.stack([m.interval_firing(lo, hi)[0] for m in self.mfs[name]], axis=1)
            mu = np.stack([m.interval_firing(lo, hi)[1] for m in self.mfs[name]], axis=1)
            out[name] = (ml, mu)
        return out

    def infer_it2(self, intervals: dict) -> dict:
        ant, cl, cr = self._rule_arrays()
        mem = self.term_memberships_it2(intervals)
        f_lo = np.ones((len(np.atleast_1d(intervals["level"][0])), len(RULES)))
        f_hi = f_lo.copy()
        for j, name in enumerate(INPUTS):
            f_lo *= mem[name][0][:, ant[:, j]]
            f_hi *= mem[name][1][:, ant[:, j]]
        yl, yr = type_reduce(cl, cr, f_lo, f_hi)
        return {"yl": yl, "yr": yr, "y": (yl + yr) / 2.0, "f_lo": f_lo, "f_hi": f_hi}

    def infer_t1(self, crisp: dict) -> dict:
        ant, cl, cr = self._rule_arrays()
        c = (cl + cr) / 2.0
        n = len(np.atleast_1d(crisp["level"]))
        f = np.ones((n, len(RULES)))
        for j, name in enumerate(INPUTS):
            x = np.asarray(crisp[name], float)
            mu = np.stack([m.embedded(x) for m in self.mfs[name]], axis=1)
            f *= mu[:, ant[:, j]]
        s = f.sum(axis=1)
        with np.errstate(invalid="ignore", divide="ignore"):
            y = np.where(s > 0, (f * c).sum(axis=1) / s, np.nan)
        return {"y": y, "f": f}

    def describe(self) -> dict:
        return {
            "inputs": {n: [{"term": TERMS[n][i], "lower": m.lower.to_dict(), "upper": m.upper.to_dict(),
                            "type1": m.embedded.to_dict()} for i, m in enumerate(self.mfs[n])] for n in INPUTS},
            "consequents": CONSEQUENTS,
            "rules": rule_table(),
            "t_norm": "product",
            "type_reduction": "center-of-sets, Karnik-Mendel (exact switch-point search, verified against iterative KM)",
            "defuzzification": "midpoint (yl + yr) / 2",
        }
