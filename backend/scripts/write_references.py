"""Render REFERENCES.md (repo root) from the single sources the dashboard also uses:
floodguard/references.py (literature), datasets/registry.py (dataset metadata), the quality reports of the
imported files, and results/comparison_<ds>.json (splits, label counts).

    python scripts/write_references.py
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from floodguard import config  # noqa: E402
from floodguard.datasets import DATASETS, load_quality  # noqa: E402
from floodguard.references import ACCESSED, DATA_SOURCES_CHECKED, REFERENCES  # noqa: E402

COLUMNS = {
    "t_hours": "hours since the first record (derived)",
    "timestamp": "record time as given in the source (empty for Malwathu: no dates in the file)",
    "level": "river water level [m]",
    "rain__<sensor>": "rainfall per step for each sensor (gauge / radar cell mean / station gauges); unit see notes",
    "step_ok": "True when the previous record is exactly one nominal step earlier (derived)",
    "rise_rate": "level change per hour over exactly one nominal step [m/h], NaN across gaps (derived)",
}


def main():
    md = ["# HydroSentinel AI: dataset and research references", "",
          f"Generated by `backend/scripts/write_references.py`. DOIs resolved through the Crossref REST API on {ACCESSED}; "
          "dataset facts are computed from the files actually downloaded (SHA-256 checked).", "",
          "## 1. Datasets used", ""]
    for ds_id, spec in DATASETS.items():
        q = load_quality(ds_id) or {}
        cmp_f = config.RESULTS_DIR / f"comparison_{ds_id}.json"
        meta = json.loads(cmp_f.read_text())["meta"] if cmp_f.exists() else None
        md += [f"### {spec.name}", "",
               "| Item | Value |", "|---|---|",
               f"| Original publisher | Authors' public repository accompanying: {spec.paper_ref}, \"{spec.paper_title}\" |",
               f"| DOI | [{spec.doi}](https://doi.org/{spec.doi}) |",
               f"| Landing page / download | {spec.repo} (commit `{spec.repo_commit}`); files: "
               + ", ".join(f"[{f.name}]({f.url}) ({f.size:,} bytes, SHA-256 `{f.sha256[:16]}…`)" for f in spec.files) + " |",
               f"| Licence / attribution | {spec.licence}. Cite the paper above when using the data. |",
               f"| Geographic coverage | {spec.location} |",
               f"| Period | {spec.period_claimed} |",
               f"| Records | {q.get('rows', 'not imported'):,} rows; {q.get('gaps', '?')} timestamp gaps (largest {q.get('largest_gap_hours', '?')} h) |"
               if q else "| Records | not imported |",
               f"| Sampling | {spec.resolution} |",
               f"| Rain sensors | {', '.join(spec.rain_sensors)} |",
               f"| Missing values in the source | {q.get('missing_values', '?')} |",
               f"| Access date | {q.get('imported_at', '?')[:10]} (download), {ACCESSED} (metadata check) |", ""]
        md += ["Original columns → standard fields:", ""] + [f"* `{k}`: {v}" for k, v in spec.column_mapping.items()] + [""]
        md += ["Processed columns:", ""] + [f"* `{k}`: {v}" for k, v in COLUMNS.items()] + [""]
        if q.get("processing_steps"):
            md += ["Preprocessing steps:", ""] + [f"{i}. {s}" for i, s in enumerate(q["processing_steps"], 1)] + [""]
        md += ["**Target variable and labels (PROXY, not recorded floods).** " + spec.label_info["description"]
               + " The label at horizon h is the class of the observed level exactly h steps later, computed from the "
               "original (uncorrupted) data; Alert = High or Critical.", ""]
        if meta:
            t = meta["train"]
            md += [f"**Splits (chronological):** fit block {t['fit_rows']:,} rows ({t['first']} to {t['fit_last']}); "
                   f"validation {t['validation_rows']:,} rows (from {t['validation_first']} to {t['last']}); "
                   f"test {meta['test']['rows']:,} rows ({meta['test']['first']} to {meta['test']['last']}). "
                   f"Horizons: {', '.join(meta['horizons'].values())}"
                   + (f"; not supported: {'; '.join(meta['unsupported_horizons'])}" if meta["unsupported_horizons"] else "")
                   + ".", ""]
        md += ["Known limitations:", ""] + [f"* {x}" for x in spec.limitations] + [""]
        if spec.unverified:
            md += ["Not independently verified:", ""] + [f"* {x}" for x in spec.unverified] + [""]
    md += ["## 2. Official data portals considered (NOT used)", "",
           "| Portal | Status |", "|---|---|"]
    md += [f"| {x['name']}{' (' + x['url'] + ')' if x['url'] else ''} | {x['status']} |" for x in DATA_SOURCES_CHECKED]
    md += ["", "No data in this project comes from IMD, CWC or India-WRIS.", "",
           "## 3. Literature", ""]
    for topic in dict.fromkeys(r["topic"] for r in REFERENCES):
        md += [f"### {topic}", ""]
        for r in (x for x in REFERENCES if x["topic"] == topic):
            md.append(f"* {r['authors']} ({r['year']}). *{r['title']}*. {r['venue']}. "
                      f"DOI: [{r['doi']}](https://doi.org/{r['doi']})" + (f" · {r['url']}" if r["url"] else "")
                      + f"  \n  *Supports:* {r['supports']}")
        md.append("")
    md += ["## 4. Research gap (relative to the works above, not a systematic review)", "",
           "The techniques are established individually. The integration studied here is per-sensor reliability assessment → "
           "interval-preserving fusion → IT2FIS, with SOM / Fuzzy ART pattern familiarity changing only the confidence "
           "status, and flood risk and confidence reported separately. The project also contributes a seeded, like-for-like "
           "comparison under 11 simulated sensor-fault scenarios and several horizons. Whether the integration helps is "
           "reported per scenario in `results/MODEL_COMPARISON_<dataset>.md`; it is not assumed.", ""]
    out = config.ROOT / "REFERENCES.md"
    out.write_text("\n".join(md), encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
